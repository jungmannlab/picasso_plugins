def group_indices(locs: pd.DataFrame) -> dict[int, np.ndarray]:
    """Map each group id to the positional indices of its localizations.

    ``DataFrame.groupby(...).indices`` already returns exactly this, but we
    force Python ``int`` keys and ``int64`` index arrays so the result can
    be passed across thread boundaries without dtype surprises.
    """
    return {
        int(g): np.asarray(idx, dtype=np.int64)
        for g, idx in locs.groupby("group").indices.items()
    }


def rotation_search(hist_2d: np.ndarray, ref_2d: np.ndarray) -> float:
    """Return the in-plane angle (degrees) maximizing the 2D overlap.

    ``hist_2d`` and ``ref_2d`` are xy histograms on the same grid, with
    axis 0 = x and axis 1 = y. The returned angle is the one to apply to
    the group's coordinates with the standard counter-clockwise matrix
    ``[[cos, -sin], [sin, cos]]``, which matches how
    ``scipy.ndimage.rotate`` moves image content for these axes.

    Two-stage search:

    1. Coarse sweep over ``[0, 360)`` in ``ANGLE_COARSE_STEP`` increments.
    2. Fine sweep over ``best +/- ANGLE_COARSE_STEP`` in ``ANGLE_FINE_STEP``
       increments.

    The output is always normalized to ``[0, 360)`` so it composes cleanly
    across iterations in :func:`compose`.
    """

    def best_of(angles):
        # Return the angle maximizing the sum of element-wise product with
        # the reference (unnormalized cross-correlation). No normalization
        # is needed because all candidate rotations have identical total
        # intensity (rotation preserves the sum), so the raw product is a
        # monotonic proxy for normalized correlation.
        best_angle, best_cc = 0.0, -np.inf
        for angle in angles:
            rotated = rotate(hist_2d, angle, reshape=False, order=1)
            cc = float(np.sum(rotated * ref_2d))
            if cc > best_cc:
                best_cc, best_angle = cc, float(angle)
        return best_angle, best_cc

    coarse, _ = best_of(np.arange(0.0, 360.0, ANGLE_COARSE_STEP))
    fine, _ = best_of(
        np.arange(
            coarse - ANGLE_COARSE_STEP,
            coarse + ANGLE_COARSE_STEP + 1e-9,
            ANGLE_FINE_STEP,
        )
    )
    return float(fine % 360.0)


def align_group(
    x_cam: np.ndarray,
    y_cam: np.ndarray,
    z_nm: np.ndarray,
    ref_hist: np.ndarray,
    ref_2d: np.ndarray,
    edges: np.ndarray,
    pixel_size: float,
) -> tuple[float, float, float, float]:
    """Align one group to the reference maps.

    This is the numerical heart of the plugin. For a single picked
    structure it returns the rigid transform (in-plane angle + 3D
    translation) that best matches the current consensus. The caller is
    responsible for actually applying the transform and for accumulating
    it in the per-group transform record.

    Parameters
    ----------
    x_cam, y_cam : np.ndarray
        Group coordinates in camera pixels, centered on the origin.
    z_nm : np.ndarray
        Group z coordinates in nm, centered on the origin.
    ref_hist : np.ndarray
        3D histogram of all localizations on the ``edges`` grid (nm).
    ref_2d : np.ndarray
        ``ref_hist`` summed along z.
    edges : np.ndarray
        Shared bin edges in nm for all three axes. Must be identical for
        the reference and the group so that voxels correspond 1:1.
    pixel_size : float
        Camera pixel size in nm, used to convert x/y to nm before binning.

    Returns
    -------
    angle_deg : float
        In-plane rotation to apply to the group (counter-clockwise,
        degrees, in ``[0, 360)``).
    dx_cam, dy_cam : float
        Translation in camera pixels, applied *after* the rotation.
    dz_nm : float
        Translation in nm along z.

    Notes
    -----
    * A group that lies entirely outside the histogram box returns the
      identity transform. This is preferable to crashing on a single
      badly-picked group, and its COM was already correctly subtracted by
      the caller.
    * Only one round of (rotation -> translation) is performed here. The
      iteration needed to converge on the consensus is done by the caller
      in :meth:`AlignWorker._run`; this keeps ``align_group`` free of any
      state and easy to parallelize.
    """
    # Histogram the group in xy on the shared edges. Converting to nm here
    # (rather than binning in pixels) makes the histogram directly
    # comparable to the reference.
    hist_2d, _, _ = np.histogram2d(
        x_cam * pixel_size, y_cam * pixel_size, bins=(edges, edges)
    )
    if not hist_2d.any():  # group entirely outside the box - leave it alone
        return 0.0, 0.0, 0.0, 0.0

    angle_deg = rotation_search(hist_2d, ref_2d)

    # Apply the rotation in *coordinate* space (not image space) so the
    # convention matches ``rotation_search`` and, ultimately, the way the
    # transform is later replayed on the target channel.
    rad = np.radians(angle_deg)
    cos_a, sin_a = np.cos(rad), np.sin(rad)
    x_rot = x_cam * cos_a - y_cam * sin_a
    y_rot = x_cam * sin_a + y_cam * cos_a

    # Histogram the rotated group in 3D and cross-correlate with the
    # reference. Because both histograms use the same ``edges``, the lag
    # of the peak directly gives the translational offset.
    hist_3d, _ = np.histogramdd(
        (x_rot * pixel_size, y_rot * pixel_size, z_nm),
        bins=(edges, edges, edges),
    )
    if not hist_3d.any():
        return angle_deg, 0.0, 0.0, 0.0

    # Cross-correlation as a convolution with the reversed group histogram.
    # ``mode="same"`` puts zero lag at ``shape // 2`` for both even and odd
    # bin counts, so the shift is simply the peak offset from that center.
    cc_3d = fftconvolve(ref_hist, hist_3d[::-1, ::-1, ::-1], mode="same")
    peak = np.unravel_index(np.argmax(cc_3d), cc_3d.shape)
    shift_bin = np.asarray(peak) - np.asarray(cc_3d.shape) // 2

    # Use the true bin width: ``edges`` may not be an exact multiple of the
    # requested voxel size.
    bin_width = float(edges[1] - edges[0])
    return (
        angle_deg,
        float(shift_bin[0] * bin_width / pixel_size),
        float(shift_bin[1] * bin_width / pixel_size),
        float(shift_bin[2] * bin_width),
    )


def compose(
    transform: dict, angle_deg: float, dx: float, dy: float, dz: float
) -> None:
    """Fold one more iteration into a group's accumulated transform.

    Iteration *k* maps ``p -> R_k p + d_k``, so after *n* iterations the
    composite is ``R_n...R_1 p + sum_k (R_n...R_(k+1) d_k)``: the angles
    add, but every translation must be rotated by the rotations that come
    after it. Summing the raw translations (as a naive accumulator does)
    misplaces the target channel whenever a later iteration finds a
    non-zero angle.

    The function mutates ``transform`` in place. Angles are kept in
    ``[0, 360)`` for readability; translations are in the same units as
    the input (camera pixels for x/y, nm for z).
    """
    rad = np.radians(angle_deg)
    cos_a, sin_a = np.cos(rad), np.sin(rad)
    tx, ty = transform["dx"], transform["dy"]
    # New cumulative rotation is the product of the previous one and the
    # new one; angles are additive because we only rotate about z.
    transform["angle_deg"] = float(
        (transform["angle_deg"] + angle_deg) % 360.0
    )
    # Rotate the *old* translation by the *new* rotation before adding the
    # new translation, so that the total still equals R_total * p + d_total.
    transform["dx"] = float(tx * cos_a - ty * sin_a + dx)
    transform["dy"] = float(tx * sin_a + ty * cos_a + dy)
    transform["dz"] = float(transform["dz"] + dz)


def apply_transform(
    x: np.ndarray,
    y: np.ndarray,
    z: np.ndarray,
    com: dict,
    cc: dict,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Apply a recorded transform: center on the reference COM, then
    rotate in plane and translate. Returns origin-centered coordinates.

    This is the exact inverse of the operation performed during the
    reference alignment, which is what makes channel-to-channel replay
    possible.
    """
    # Step 1: bring the group to its own center of mass (the same COM that
    # was subtracted from the reference group during alignment).
    x = np.asarray(x, dtype=np.float64) - com["com_x"]
    y = np.asarray(y, dtype=np.float64) - com["com_y"]
    z = np.asarray(z, dtype=np.float64) - com["com_z"]

    # Step 2: apply the accumulated rigid transform.
    rad = np.radians(cc["angle_deg"])
    cos_a, sin_a = np.cos(rad), np.sin(rad)
    return (
        x * cos_a - y * sin_a + cc["dx"],
        x * sin_a + y * cos_a + cc["dy"],
        z + cc["dz"],
    )


