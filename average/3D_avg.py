# These helpers translate between the plugin's internal DataFrame and the
# on-disk format expected by Picasso. They deliberately delegate to
# ``picasso.average`` and ``picasso.io`` so that files saved here are
# byte-compatible with the built-in Average plugin.


def ensure_required_metadata(
    info: list[dict], locs: pd.DataFrame, pixel_size: float
) -> list[dict]:
    """Return a copy of ``info`` with the keys Picasso requires downstream.

    ``lib.ensure_sanity`` needs ``Width``, ``Height`` and ``Frames``, and
    ``average.prepare_locs_for_save`` needs ``Width``/``Height`` to place
    the structure on the canvas. Existing values are never overwritten -
    only genuinely missing ones are filled in, so acquisition metadata
    stays intact.

    The localizations are expected to be origin-centered when this is
    called; ``Width``/``Height`` are computed from the extent of the
    data around the origin, which is a reasonable default for picked
    structures that have already been COM-aligned.
    """
    info = [dict(entry) for entry in (info or [{}])]
    first = info[0]
    if lib.get_from_metadata(info, "Width") is None:
        first["Width"] = int(np.ceil(locs["x"].max() - locs["x"].min())) or 1
    if lib.get_from_metadata(info, "Height") is None:
        first["Height"] = int(np.ceil(locs["y"].max() - locs["y"].min())) or 1
    if lib.get_from_metadata(info, "Frames") is None:
        first["Frames"] = (
            int(locs["frame"].max()) + 1 if "frame" in locs.columns else 1
        )
    if lib.get_from_metadata(info, "Pixelsize") is None:
        first["Pixelsize"] = float(pixel_size)
    return info


def save_aligned_locs(
    path: str, locs: pd.DataFrame, info: list[dict], params: dict
) -> None:
    """Save origin-centered localizations the way the Average GUI does.

    ``prepare_locs_for_save`` shifts x/y onto the canvas
    (``+Width/2``, ``+Height/2``) and appends a provenance entry, which is
    then extended with this plugin's parameters.

    The ``Generated by`` string is deliberately set to ``Picasso <ver>
    Average`` (not the plugin name) so that the file loads without
    warnings in older Picasso versions that check this field, and so that
    the plugin is listed separately under its own key.
    """
    out_locs, out_info = average.prepare_locs_for_save(locs.copy(), info)
    out_info[-1]["Generated by"] = f"Picasso {__version__} Average"
    out_info[-1][PLUGIN_NAME] = params
    io.save_locs(path, out_locs, out_info)


def load_transformations(path: str) -> tuple[dict[int, dict], dict]:
    """Read a ``*_3DTransformations.yaml`` file.

    Returns the per-group transforms plus the ``__meta__`` block (empty
    for files written before it existed). Group entries are normalized to
    the nested ``com_transform``/``cc_transform`` layout, so callers do
    not have to know which plugin version produced the file.

    Two on-disk layouts are supported:

    * **Current** - ``{group: {com_transform: {...}, cc_transform: {...}}}``
    * **Legacy** - flat dictionaries with keys ``com_x``, ``angle_deg``,
      etc., as written by early versions of this plugin.
    """
    with open(path, "r") as f:
        docs = [d for d in yaml.safe_load_all(f) if isinstance(d, dict)]

    raw: dict = {}
    for doc in docs:
        raw.update(doc)

    meta = raw.pop("__meta__", {}) or {}
    transformations: dict[int, dict] = {}
    for key, entry in raw.items():
        try:
            group = int(key)
        except (TypeError, ValueError):
            continue
        if not isinstance(entry, dict):
            continue
        if "com_transform" in entry and "cc_transform" in entry:
            com, cc = entry["com_transform"], entry["cc_transform"]
        else:  # flat layout written by older versions of this plugin
            com = {k: entry.get(k, 0.0) for k in ("com_x", "com_y", "com_z")}
            cc = {
                k: entry.get(k, 0.0) for k in ("angle_deg", "dx", "dy", "dz")
            }
        transformations[group] = {"com_transform": com, "cc_transform": cc}
    return transformations, meta


