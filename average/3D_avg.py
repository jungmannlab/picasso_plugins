"""
Picasso Average plugin: 2D in-plane rotation + 3D translation alignment
of picked structures, with a reference channel whose transformations can
be replayed onto a target channel.

--------------------------------------------------------------------------------
Installation
--------------------------------------------------------------------------------
Drop this file into Picasso's plugin directory:

    ~/.picasso/plugins/           (Linux / macOS)
    %USERPROFILE%\\.picasso\\plugins\\  (Windows)

Restart Picasso, open the *Average* window, and you will find the plugin
under the ``Plugins`` menu.

--------------------------------------------------------------------------------
Workflow overview
--------------------------------------------------------------------------------
This plugin implements the standard two-channel averaging alignment used
for correlative SMLM:

1. **Reference channel alignment** - ``3D COM & 2D rotation cross-correlation``
   * Every group (picked structure) is centered on its own 3D center of mass.
   * The group is then iteratively aligned to the consensus (reference)
     histograms by searching for the in-plane rotation and 3D translation
     that maximize cross-correlation with the current average.
   * The final aligned reference localizations are written as
     ``<basename>_3DAligned.hdf5`` and the per-group transforms as
     ``<basename>_3DTransformations.yaml``.

2. **Target channel alignment** - ``Apply saved reference transformations
   to target channel``
   * Reads the transform YAML produced in step 1.
   * Replays the exact same rigid transforms (COM, rotation, translation)
     on a second channel, using ``group`` id as the correspondence key.
   * Writes ``<basename>_3DAligned.hdf5`` for the target.

This two-step design means the target channel never re-aligns; it is
*carried along* by the reference. That is the standard way to preserve
relative registration between two channels in correlative SMLM.

--------------------------------------------------------------------------------
Coordinate and unit conventions (must match ``picasso.gui.average``)
--------------------------------------------------------------------------------
* Localizations are held in a ``pandas.DataFrame`` with columns:
    - ``x``, ``y`` : camera pixels (float)
    - ``z``        : nanometers (float)
    - ``group``    : integer, one per picked structure
* While averaging, groups are centered on the origin. The canvas offset
  (``Width / 2``, ``Height / 2``) is added only on save, by
  ``picasso.average.prepare_locs_for_save``. This mirrors exactly what the
  built-in Average plugin does, so downstream features (File > Save,
  Process > Average, undo, etc.) keep working.
* Histogram bin edges for cross-correlation are in **nanometers**;
  ``align_group`` converts camera-pixel x/y into nm before binning.

--------------------------------------------------------------------------------
Threading model
--------------------------------------------------------------------------------
* The heavy alignment runs in a dedicated ``QThread`` (``AlignWorker``) so
  the GUI stays responsive.
* Within each iteration, groups are aligned in parallel using a
  ``ThreadPoolExecutor``. Each thread does NumPy/SciPy work that releases
  the GIL, so we get real parallelism without the cost of forking.
* ``threadpoolctl`` caps BLAS/OpenMP backends to one thread per worker,
  preventing the classic oversubscription (N_workers x N_BLAS_threads)
  that degrades performance and sometimes crashes on large grids.

author: Aditya Chhatre
"""

